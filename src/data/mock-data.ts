// Fonction pour formater le prix
export const formatPrice = (price: number): string => {
  const value = Number.isFinite(price) ? Math.round(price) : 0;
  return `${value} FCFA`;
};

// Calculer les statistiques
export const getStats = (): Stats => {
  const approved = properties.filter(p => p.status === 'available');
  const pending = properties.filter(p => p.status === 'available');
  const sold = properties.filter(p => p.status === 'occupied');
  
  const types: PropertyType[] = ['house', 'apartment', 'land', 'shop'];
  const propertiesByType = types.map(type => ({
    type,
    count: properties.filter(p => p.type === type).length,
  }));

  return {
    totalProperties: properties.length,
    totalClients: clients.length,
    pendingProperties: pending.length,
    soldProperties: sold.length,
    totalValue: properties.reduce((sum, p) => sum + p.price, 0),
    propertiesByType,
  };
};

// Obtenir les biens en vedette
export const getFeaturedProperties = (): Property[] => {
  return properties.filter(p => p.featured && p.status === 'available');
};

// Filtrer les biens par type
export const getPropertiesByType = (type: PropertyType): Property[] => {
  return properties.filter(p => p.type === type && p.status === 'available');
};

// Rechercher des biens
export const searchProperties = (query: string): Property[] => {
  const lowerQuery = query.toLowerCase();
  return properties.filter(
    p =>
      p.status === 'available' &&
      (p.title.toLowerCase().includes(lowerQuery) ||
        p.location.toLowerCase().includes(lowerQuery) ||
        p.description.toLowerCase().includes(lowerQuery))
  );
};



