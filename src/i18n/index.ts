type TranslationKey = keyof typeof STRINGS.fr;

let currentLanguage: Language = 'fr';

export const setCurrentLanguage = (language: Language) => {
  currentLanguage = language;
};

export const getCurrentLanguage = () => currentLanguage;

const PROPERTY_TYPE_LABELS: Record<Language, Partial<Record<PropertyType, string>>> = {
  fr: {
    house: 'Maison',
    apartment: 'Appartement',
    land: 'Terrain',
    shop: 'Boutique',
  },
  en: {
    house: 'House',
    apartment: 'Apartment',
    land: 'Land',
    shop: 'Shop',
  },
};

const STATUS_LABELS: Record<Language, Partial<Record<PropertyStatus, string>>> = {
  fr: {
    available: STRINGS.fr.status_available,
    occupied: STRINGS.fr.status_occupied,
  },
  en: {
    available: STRINGS.en.status_available,
    occupied: STRINGS.en.status_occupied,
  },
};

export const translate = (language: Language, key: TranslationKey): string => {
  const table = STRINGS[language] as Partial<Record<TranslationKey, string>> | undefined;
  const normalizedKey = key.toLowerCase() as TranslationKey;
  return table?.[key] ?? table?.[normalizedKey] ?? STRINGS.fr[normalizedKey] ?? key;
};

export const translateType = (language: Language, type: PropertyType): string => {
  return PROPERTY_TYPE_LABELS[language]?.[type] ?? PROPERTY_TYPE_LABELS.fr[type] ?? type;
};

export const translateStatus = (language: Language, status: PropertyStatus): string => {
  return STATUS_LABELS[language]?.[status] ?? STATUS_LABELS.fr[status] ?? status;
};

export type { TranslationKey };
