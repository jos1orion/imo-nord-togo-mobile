export const translate = (language: Language, key: TranslationKey): string => {
  const table = STRINGS[language] as Partial<Record<TranslationKey, string>> | undefined;
  return table?.[key] ?? STRINGS.fr[key] ?? key;
};

export const translateType = (language: Language, type: PropertyType): string => {
  return PROPERTY_TYPE_LABELS[language]?.[type] ?? PROPERTY_TYPE_LABELS.fr[type] ?? type;
};

export const translateStatus = (language: Language, status: PropertyStatus): string => {
  return STATUS_LABELS[language]?.[status] ?? STATUS_LABELS.fr[status] ?? status;
};

